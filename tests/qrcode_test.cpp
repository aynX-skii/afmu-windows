int main()
{
    std::fprintf(stderr, "== 对照 segno 的 %zu 组向量 ==\n",
                 sizeof(kVectors) / sizeof(kVectors[0]));
    int mismatch = 0;
    for (const Vector &v : kVectors) {
        const QByteArray data = genData(v.seed, v.length);
        const afmu::QrCode qr = afmu::QrCode::encode(data, afmu::QrCode::Ecc(v.ecc));
        if (!qr.isValid() || qr.version() != v.version || qr.size() != v.version * 4 + 17
            || digestOf(qr) != QByteArray(v.digest)) {
            if (++mismatch <= 10) {
                std::fprintf(stderr, "  失败：版本 %d 级别 %d 长度 %d —— 得到 版本 %d 摘要 %s\n",
                             v.version, v.ecc, v.length, qr.version(),
                             digestOf(qr).constData());
            }
        }
    }
    check(mismatch == 0, "全部向量应当逐位一致");
    if (mismatch == 0)
        std::fprintf(stderr, "  %zu 组全部一致\n", sizeof(kVectors) / sizeof(kVectors[0]));

    // ------------------------------------------------------------ 人眼可读的那一张
    {
        const afmu::QrCode qr =
            afmu::QrCode::encode(QByteArrayLiteral("afmu"), afmu::QrCode::Ecc::Medium);
        check(qr.isValid() && qr.version() == 1 && qr.size() == 21, "\"afmu\" 应当是版本 1");
        bool same = qr.size() == 21;
        for (int y = 0; y < qr.size() && same; ++y) {
            for (int x = 0; x < qr.size(); ++x) {
                if (qr.module(x, y) != (kAfmuArt[y][x] == '#')) {
                    same = false;
                    std::fprintf(stderr, "  第 %d 行不一致\n    期望 %s\n    实际 ", y,
                                 kAfmuArt[y]);
                    for (int i = 0; i < qr.size(); ++i)
                        std::fputc(qr.module(i, y) ? '#' : '.', stderr);
                    std::fputc('\n', stderr);
                    break;
                }
            }
        }
        check(same, "\"afmu\" 的位图应当和参考图一致");
    }

    // ------------------------------------------------------------ 边界
    {
        check(!afmu::QrCode::encode(QByteArray(), afmu::QrCode::Ecc::Medium).isValid(),
              "空数据应当返回无效对象而不是崩");
        // 版本 40 的字节模式容量：L 2953 / M 2331 / Q 1663 / H 1273
        const struct { afmu::QrCode::Ecc ecc; int cap; } caps[] = {
            { afmu::QrCode::Ecc::Low, 2953 },
            { afmu::QrCode::Ecc::Medium, 2331 },
            { afmu::QrCode::Ecc::Quartile, 1663 },
            { afmu::QrCode::Ecc::High, 1273 },
        };
        for (const auto &c : caps) {
            const afmu::QrCode ok = afmu::QrCode::encode(QByteArray(c.cap, 'x'), c.ecc);
            check(ok.isValid() && ok.version() == 40, "满容量应当编得出版本 40");
            check(!afmu::QrCode::encode(QByteArray(c.cap + 1, 'x'), c.ecc).isValid(),
                  "超一个字节就应当失败，不能悄悄截断");
        }
    }

    // 越界读取要当成浅色 —— QrImage 画静区时直接带着负坐标循环
    {
        const afmu::QrCode qr =
            afmu::QrCode::encode(QByteArrayLiteral("afmu"), afmu::QrCode::Ecc::Medium);
        check(!qr.module(-1, 0) && !qr.module(0, -1) && !qr.module(21, 0) && !qr.module(0, 21),
              "越界应当当成浅色");
    }

    std::fprintf(stderr, "\n通过 %d / 失败 %d\n", g_passed, g_failed);
    return g_failed == 0 ? 0 : 1;
}
